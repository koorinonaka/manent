/// `language` は設定値 (`auto` / `ja` / `en`)。`auto` は OS の UI 言語で、ja 以外は en。
pub fn is_ja(language: &str) -> bool {
    match language {
        "ja" => true,
        "en" => false,
        _ => os_is_japanese(),
    }
}

pub fn pick(ja: bool) -> &'static Strings {
    if ja { &JA } else { &EN }
}

fn os_is_japanese() -> bool {
    const LANG_JAPANESE: u16 = 0x11;
    // 下位 10 bit が primary language。
    unsafe { windows::Win32::Globalization::GetUserDefaultUILanguage() & 0x3FF == LANG_JAPANESE }
}
