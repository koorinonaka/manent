/// `language` は設定値 (`auto` / `ja` / `en`)。`auto` は OS の UI 言語で、ja 以外は en。
pub fn is_ja(language: &str) -> bool {
    match language {
        "ja" => true,
        "en" => false,
        _ => os_is_japanese(),
    }
}

pub fn pick(ja: bool) -> &'static Strings {
    if ja { &JA } else { &EN }
}

fn os_is_japanese() -> bool {
    const LANG_JAPANESE: u16 = 0x11;
    // 下位 10 bit が primary language。
    unsafe { windows::Win32::Globalization::GetUserDefaultUILanguage() & 0x3FF == LANG_JAPANESE }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// トレイのバルーンの本文は 255 文字 (UTF-16) まで。超えた分は切れて読めない。
    /// 起動時の知らせが全部重なる組み合わせ (`main` の `notices` と `welcome`) で確かめる。
    #[test]
    fn startup_balloons_fit() {
        for s in [&JA, &EN] {
            let failed = format!("{} Shift+PrintScreen", s.hotkey_failed);
            let notices = [s.takeover_failed, &failed, s.prtsc_taken, s.prtsc_hint];
            let still = s.welcome_still.replace("{key}", "PrintScreen");
            let video = s.welcome_video.replace("{key}", "Shift+PrintScreen");
            let cases = [
                [&[s.welcome][..], &notices].concat(),
                [&[s.settings_broken][..], &notices].concat(),
                vec![s.welcome, &still, &video, s.welcome_tray],
            ];
            for lines in cases {
                let text = lines.join("\n");
                let len = text.encode_utf16().count();
                assert!(len <= 255, "{len} > 255: {text}");
            }
        }
    }
}
